// Pre-generate src/cards-tsv-raw.generated.ts from data/cards.tsv.
//
// Why a generator? `import x from './foo.tsv?raw'` is a Vite-only feature.
// The Cloudflare Pages Functions bundler (esbuild via wrangler) doesn't
// know about it, so the same engine imports break the API build. Emitting
// a regular TS string literal sidesteps that — both pipelines read it the
// same way, and the TSV stays the human-edit source of truth.
//
// Run automatically via `npm run prebuild` (wired into package.json) and
// `npm run predev`. Output is checked in so contributors don't need to
// remember to regenerate.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const tsvPath = path.join(root, 'data', 'cards.tsv');
const outPath = path.join(root, 'src', 'cards-tsv-raw.generated.ts');

const raw = fs.readFileSync(tsvPath, 'utf8');

const header = `// AUTOGENERATED by scripts/build-card-data.mjs from data/cards.tsv.
// Edit the TSV; this file is regenerated on every build.
// Do not edit by hand.

`;
const body = `export const CARDS_TSV: string = ${JSON.stringify(raw)};\n`;

fs.writeFileSync(outPath, header + body);
console.log(`wrote ${path.relative(root, outPath)} (${raw.length} chars)`);
