// One-shot integration script for the Ages 2-10 workflow output.
// Reads the workflow result JSON, unescapes HTML entities, writes each agent's
// handler + test file to src/engine/handlers/, regenerates handlers/index.ts.
// Run: node scripts/integrate-workflow.mjs <path-to-output-json>

import fs from 'node:fs';
import path from 'node:path';

const outputFile = process.argv[2];
if (!outputFile) {
  console.error('usage: node scripts/integrate-workflow.mjs <output.json>');
  process.exit(1);
}

const raw = fs.readFileSync(outputFile, 'utf8');
const parsed = JSON.parse(raw);
// Workflow output wraps the script's return value in `.result`.
const { ages, results } = parsed.result ?? parsed;

if (!Array.isArray(ages) || !Array.isArray(results) || ages.length !== results.length) {
  console.error('unexpected JSON shape');
  process.exit(1);
}

// HTML-entity unescaper — schema output came back with &gt; / &amp; / &lt; etc.
function unescape(s) {
  return s
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'");
}

const handlersDir = path.resolve('src/engine/handlers');
const indexImports = ["import './age1';"];

for (let i = 0; i < ages.length; i++) {
  const age = ages[i];
  const r = results[i];
  if (!r) {
    console.error(`age ${age}: agent returned null — skipping`);
    continue;
  }
  if (!r.handlerFileContent || !r.testFileContent) {
    console.error(`age ${age}: missing handlerFileContent or testFileContent`);
    continue;
  }
  const handlerPath = path.join(handlersDir, `age${age}.ts`);
  const testPath = path.join(handlersDir, `age${age}.test.ts`);
  fs.writeFileSync(handlerPath, unescape(r.handlerFileContent));
  fs.writeFileSync(testPath, unescape(r.testFileContent));
  indexImports.push(`import './age${age}';`);
  console.log(`age ${age}: wrote ${path.relative(process.cwd(), handlerPath)} + test — ${r.cards?.length ?? '?'} cards`);
  if (r.deferred && r.deferred.length > 0) {
    console.log(`  deferred (${r.deferred.length}):`);
    for (const d of r.deferred) console.log(`    - ${d}`);
  }
}

// Regenerate handlers/index.ts so every age file gets registered.
const indexPath = path.join(handlersDir, 'index.ts');
const indexHeader = `// Side-effect imports — each file registers its cards' dogma handlers at
// module load time via registerDogma. Adding a card-set is one new import.
//
// Auto-regenerated by scripts/integrate-workflow.mjs after the Ages 2-10
// workflow run. Hand edits are fine; just keep one import per age file.
`;
fs.writeFileSync(indexPath, indexHeader + indexImports.join('\n') + '\n');
console.log(`wrote ${path.relative(process.cwd(), indexPath)}`);
